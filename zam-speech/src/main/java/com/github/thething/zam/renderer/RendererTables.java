package com.github.thething.zam.renderer;

/**
 * Static look-up tables used by {@link PhonemeRenderer} for blending, pitch and amplitude scaling.
 */
public final class RendererTables {

    private static final int MIN_STRESS = 0;
    private static final int MAX_STRESS = 8;

    private static final int[] PITCHES = new int[]{
            0x00, 0x00, 0xE0, 0xE6, 0xEC, 0xF3, 0xF9, 0x00,
            0x06, 0x0C, 0x06
    };

    private static final int[] BLEND_RANK = {
            0x00, 0x1F, 0x1F, 0x1F, 0x1F, 0x02, 0x02, 0x02,
            0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x05, 0x05,
            0x02, 0x0A, 0x02, 0x08, 0x05, 0x05, 0x0B, 0x0A,
            0x09, 0x08, 0x08, 0xA0, 0x08, 0x08, 0x17, 0x1F,
            0x12, 0x12, 0x12, 0x12, 0x1E, 0x1E, 0x14, 0x14,
            0x14, 0x14, 0x17, 0x17, 0x1A, 0x1A, 0x1D, 0x1D,
            0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x1A, 0x1D,
            0x1B, 0x1A, 0x1D, 0x1B, 0x1A, 0x1D, 0x1B, 0x1A,
            0x1D, 0x1B, 0x17, 0x1D, 0x17, 0x17, 0x1D, 0x17,
            0x17, 0x1D, 0x17, 0x17, 0x1D, 0x17, 0x17, 0x17,
            0x00,
    };

    private static final int[] IN_BLEND_LENGTHS = {
            0x00, 0x02, 0x02, 0x02, 0x02, 0x04, 0x04, 0x04,
            0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04,
            0x04, 0x04, 0x03, 0x03, 0x04, 0x04, 0x03, 0x03,
            0x03, 0x03, 0x03, 0x01, 0x02, 0x03, 0x02, 0x01,
            0x03, 0x03, 0x03, 0x03, 0x01, 0x01, 0x03, 0x03,
            0x03, 0x02, 0x02, 0x03, 0x02, 0x03, 0x00, 0x00,
            0x05, 0x05, 0x05, 0x05, 0x04, 0x04, 0x02, 0x00,
            0x02, 0x02, 0x00, 0x03, 0x02, 0x00, 0x04, 0x02,
            0x00, 0x03, 0x02, 0x00, 0x02, 0x02, 0x00, 0x02,
            0x03, 0x00, 0x03, 0x03, 0x00, 0x03, 0xB0, 0xA0,
            0x00,
    };

    private static final int[] OUT_BLEND_LENGTHS = {
            0x00, 0x02, 0x02, 0x02, 0x02, 0x04, 0x04, 0x04,
            0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04,
            0x04, 0x04, 0x03, 0x02, 0x04, 0x04, 0x02, 0x02,
            0x02, 0x02, 0x02, 0x01, 0x01, 0x01, 0x01, 0x01,
            0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x02, 0x02,
            0x02, 0x01, 0x00, 0x01, 0x00, 0x01, 0x00, 0x05,
            0x05, 0x05, 0x05, 0x05, 0x04, 0x04, 0x02, 0x00,
            0x01, 0x02, 0x00, 0x01, 0x02, 0x00, 0x01, 0x02,
            0x00, 0x01, 0x02, 0x00, 0x02, 0x02, 0x00, 0x01,
            0x03, 0x00, 0x02, 0x03, 0x00, 0x02, 0xA0, 0xA0,
            0x00
    };

    private static final int[] AMPLITUDE_RESCALE = {
            0x00, 0x01, 0x02, 0x02, 0x02, 0x03, 0x03, 0x04,
            0x04, 0x05, 0x06, 0x08, 0x09, 0x0B, 0x0D, 0x0F,
            0x00
    };

    private RendererTables() {
    }

    /**
     * Returns the pitch adjustment value for the given stress level.
     *
     * @param stress the stress level (0 – 8)
     * @return the pitch adjustment for that stress level
     * @throws IllegalArgumentException if {@code stress} is out of range
     */
    public static int getPitch(int stress) {
        if (stress < MIN_STRESS || stress > MAX_STRESS) {
            throw new IllegalArgumentException("Invalid stress: " + stress);
        }

        return PITCHES[stress + 1];
    }

    /**
     * Returns the blend-rank value for the given phoneme index. Higher-ranked phonemes "win" when blending with
     * adjacent lower-ranked phonemes.
     *
     * @param index phoneme index
     * @return the blend rank
     */
    public static int getBlendRank(int index) {
        return BLEND_RANK[index];
    }

    /**
     * Returns the in-blend length for the given phoneme index. This is the number of frames the phoneme contributes to
     * the blending window on its leading edge.
     *
     * @param index phoneme index
     * @return the in-blend length in frames
     */
    public static int getInBlendLength(int index) {
        return IN_BLEND_LENGTHS[index];
    }

    /**
     * Returns the out-blend length for the given phoneme index. This is the number of frames the phoneme contributes to
     * the blending window on its trailing edge.
     *
     * @param index phoneme index
     * @return the out-blend length in frames
     */
    public static int getOutBlendLength(int index) {
        return OUT_BLEND_LENGTHS[index];
    }

    /**
     * Maps a raw amplitude value to a rescaled output amplitude using the amplitude rescale table.
     *
     * @param amplitude the raw amplitude (0 – 15)
     * @return the rescaled amplitude value
     */
    public static int getAmplitudeRescale(int amplitude) {
        return AMPLITUDE_RESCALE[amplitude];
    }
}
